// Theme v2 viewport screenshots at 393x852. Usage: node scripts/shots-v2.mjs <baseUrl> <outDir>
import { chromium } from 'playwright-core';
const base = process.argv[2] ?? 'http://localhost:4173/';
const out = process.argv[3] ?? '../shots';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await browser.newContext({ reducedMotion: 'reduce', viewport: { width: 393, height: 852 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
const settle = () => page.waitForLoadState('networkidle').catch(() => {}).then(() => page.waitForTimeout(600));
const top = (sel, pad = 10) => page.evaluate(([s, p]) => { const el = document.querySelector(s); scrollBy(0, el.getBoundingClientRect().top - p); }, [sel, pad]);
const shot = async (name) => {
  await settle();
  const r = await page.evaluate(() => [document.documentElement.scrollWidth, document.documentElement.clientWidth]);
  console.log(`${name}: ${r[0]}/${r[1]}${r[0] > r[1] ? ' OVERFLOW' : ' ok'}`);
  await page.screenshot({ path: `${out}/iphone-v2-${name}.png` });
};
const roster = (n) => page.locator(`.roster-cell[aria-label$=" ${n}"]`).first().click();

await page.goto(`${base}#/draft`);
await page.evaluate(() => localStorage.setItem('dc:settings', JSON.stringify({ tourDone: true, favorites: [], sorts: { roster: { by: 'name', dir: 'asc' }, brawlers: { by: 'class', dir: 'asc' } } })));
await page.goto(`${base}#/draft?map=hard-rock-mine-gem-grab`); await page.reload();
await page.waitForSelector('.roster-cell');
for (const n of ['Kit', 'Mortis', 'Sandy', 'Gus', 'Byron', 'Bea']) await roster(n);
await roster('Gene'); await roster('Bull'); await roster('Piper');
await page.waitForSelector('.rec');
await page.evaluate(() => scrollTo(0, 0));
await shot('draft-midway');
await page.locator('.rec-main').first().click();
await top('.rec.open', 70);
await shot('breakdown-open');
await page.locator('.rec.open .btn.primary').click();
await roster('Poco'); await roster('Edgar');
await page.waitForSelector('.full-read');
await top('.full-read');
await shot('full-draft-lean-lanes');
await page.locator('.btn.danger', { hasText: 'Reset' }).click();
await page.locator('.roster .sort-ctl').getByRole('radio', { name: 'Rarity' }).click();
await top('.roster');
await shot('roster-rarity');
await page.goto(`${base}#/brawlers`); await page.waitForSelector('.b-card');
await page.evaluate(() => scrollTo(0, 0));
await shot('brawlers-class');
await page.goto(`${base}#/me`); await page.waitForSelector('.preset');
await page.evaluate(() => scrollTo(0, 0));
await shot('settings');
console.log('page errors:', errs.length ? errs : 'none');
await browser.close();
