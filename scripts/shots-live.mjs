// Mobile screenshots of the one-screen app. Usage: node scripts/shots-live.mjs <baseUrl> <outDir> [prefix]
import { chromium } from 'playwright-core';
const base = process.argv[2] ?? 'http://localhost:4173/';
const out = process.argv[3] ?? '../shots';
const prefix = process.argv[4] ?? 'simple';
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--no-sandbox'] });
const ctx = await browser.newContext({ viewport: { width: 393, height: 852 }, deviceScaleFactor: 3, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errs = [];
page.on('pageerror', (e) => errs.push(e.message));
const settle = () => page.waitForLoadState('networkidle').catch(() => {}).then(() => page.waitForTimeout(700));
const shot = async (name) => { await settle(); await page.screenshot({ path: `${out}/${prefix}-${name}.png` }); console.log(`${out}/${prefix}-${name}.png`); };
const type = async (sel, text) => { await page.locator(sel).fill(text); await page.waitForTimeout(150); await page.locator(sel).press('Enter'); await page.waitForTimeout(150); };

await page.goto(base);
await page.evaluate(() => localStorage.clear());
await page.reload();
await page.waitForFunction(() => document.body.innerText.includes('Based on'), null, { timeout: 20000 });
console.log(await page.locator('.sub').innerText());
await page.locator('input[aria-label="Search maps"]').focus();
const nMaps = await page.locator('.results li button').count();
console.log('maps in search:', nMaps);
await shot('1-map-search');
await page.locator('input[aria-label="Search maps"]').fill('hard rock');
await page.locator('.results li button').first().click();
for (const b of ['Mr. P', 'Rico', 'Chester', 'Amber', 'Bo', 'Surge']) await type('input[placeholder^="Search a brawler to ban"]', b);
console.log('top picks after 6 bans:', (await page.locator('.sugg li').allInnerTexts()).slice(0, 5).map((t) => t.replace(/\s+/g, ' ')).join(' | '));
await page.evaluate(() => { const el = document.querySelector('.sugg'); scrollBy(0, el.getBoundingClientRect().top - 260); });
await shot('2-top-picks');
// 1-2-2-1: us, them, them, us, us, them
await page.locator('.sugg li button').first().click();
for (const b of ['Gale', 'Griff']) await type('input[placeholder^="Search a pick"]', b);
await page.locator('.sugg li button').first().click();
await page.locator('.sugg li button').first().click();
await type('input[placeholder^="Search a pick"]', 'Squeak');
await page.evaluate(() => { const el = [...document.querySelectorAll('h2')].find((h) => h.textContent.includes('Lane')); scrollBy(0, el.getBoundingClientRect().top - 330); });
console.log('lanes:', (await page.locator('.lane').allInnerTexts()).map((t) => t.replace(/\s+/g, ' ')).join(' | '));
await shot('3-lanes');
if (errs.length) console.log('page errors:', errs);
await browser.close();
